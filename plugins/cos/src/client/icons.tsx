export function fileKind(name: string): FileKind {
  const lower = name.toLowerCase()
  const readme = lower === 'readme' || lower.startsWith('readme.')
  if (readme) return 'markdown'
  const dot = lower.lastIndexOf('.')
  if (dot < 0) return 'other'
  return KIND_BY_EXTENSION[lower.slice(dot + 1)] ?? 'other'
}

